import math


def area(r):
    """
    Принимает на вход радиус круга, возвращает площадь круга 
    
    Пример вызова:
      area(2)
    """

    return math.pi * r * r


def perimeter(r):
    """
    Принимает на вход радиус окружности, вохвращает её периметр

    Пример вызова:
        perimetr(3)
    """
    return 2 * math.pi * r

